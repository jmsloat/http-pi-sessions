// Explicitly scripted demo of the Pi RPC protocol. No LLM and no workspace tools.
import {createInterface} from 'node:readline';
import {readFileSync, writeFileSync} from 'node:fs';
const file = process.argv[2];
let messages = [];
try { messages = JSON.parse(readFileSync(file, 'utf8')); } catch {}
let generation = 0, waiting = false, active = false;
const models = [{provider:'demo',id:'scripted-demo',name:'Scripted demo',reasoning:true},{provider:'demo',id:'scripted-fast',name:'Scripted fast',reasoning:false}];
let model = models.find(m=>m.id===process.argv[3]) || models[0], thinkingLevel=process.argv[4] || 'off';
const emit = value => process.stdout.write(JSON.stringify(value) + '\n');
const save = () => { if(file) writeFileSync(file, JSON.stringify(messages)); };
const response = (cmd, data = {}) => emit({type:'response', id:cmd.id, command:cmd.type, success:true, data});
const taskList = [{id:1,title:'Inspect the session integration',status:'done'}, {id:2,title:'Collect your preference',status:'in_progress',note:'Waiting for your answer'}, {id:3,title:'Verify the result',status:'pending'}];
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function say(text, run) {
  const message = {role:'assistant',content:[{type:'text',text:''}]};
  emit({type:'message_start',message});
  for(const word of text.split(' ')) {
    await sleep(60);
    if(run !== generation) return false;
    message.content[0].text += word + ' ';
    emit({type:'message_update',message,assistantMessageEvent:{type:'text_delta',delta:word+' '}});
  }
  messages.push(message); save(); emit({type:'message_end',message}); return true;
}
function todo(tasks) {
  const id = 'todo-' + Date.now();
  const result = {content:[{type:'text',text:'Plan updated'}],details:{gentleTodo:{tasks,nextId:4,updatedTurn:messages.filter(m=>m.role==='user').length}}};
  emit({type:'tool_execution_start',toolCallId:id,toolName:'todo',args:{action:'write',tasks}});
  emit({type:'tool_execution_end',toolCallId:id,toolName:'todo',result,isError:false});
  const message = {role:'toolResult',toolName:'todo',toolCallId:id,...result};
  messages.push(message); save(); emit({type:'message_end',message});
}
async function handle(cmd) {
  if(cmd.type==='get_state') return response(cmd,{isStreaming:active,sessionFile:file,model,thinkingLevel});
  if(cmd.type==='get_available_models') return response(cmd,{models});
  if(cmd.type==='set_model') { model=models.find(m=>m.provider===cmd.provider&&m.id===cmd.modelId)||model; if(!model.reasoning)thinkingLevel='off'; return response(cmd,model); }
  if(cmd.type==='set_thinking_level') { thinkingLevel=model.reasoning?cmd.level:'off'; return response(cmd); }
  if(cmd.type==='get_messages') return response(cmd,{messages});
  if(cmd.type==='abort') { generation++; active=false; waiting=false; emit({type:'agent_end'}); emit({type:'agent_settled'}); return response(cmd); }
  if(cmd.type==='prompt') {
    if(active) return emit({type:'response',id:cmd.id,command:cmd.type,success:false,error:'Already working'});
    const run = ++generation; active=true; response(cmd,{disposition:'started'}); emit({type:'agent_start'});
    emit({type:'extension_ui_request',id:'clear',method:'setWidget',widgetKey:'gentle-todo'});
    const message = {role:'user',content:cmd.message}; messages.push(message);save();emit({type:'message_start',message});emit({type:'message_end',message});
    if(!await say('This is the scripted integration demo. I will update a three-step plan, ask a question, and keep this session alive if you refresh or close the page.',run)) return;
    todo(taskList);
    waiting=true;
    emit({type:'extension_ui_request',id:'demo-choice',method:'select',title:'Which behavior should we verify next?',options:['Reconnect while working','Inspect task updates']});
  }
  if(cmd.type==='extension_ui_response' && waiting && cmd.id==='demo-choice') {
    waiting=false;const run=generation;
    todo(taskList.map((t,i)=>({...t,status:i<2?'done':'in_progress',note:undefined})));
    if(!await say(cmd.cancelled?'Question cancelled. The session remains usable.':'Your answer reached the agent: '+cmd.value+'. The controller kept the task list and pending question independently of the page. This verifies the demo flow; live mode uses your configured Pi and Gentle tools.',run)) return;
    todo(taskList.map(t=>({...t,status:'done',note:undefined}))); active=false;emit({type:'agent_end'});emit({type:'agent_settled'});
  }
}
// The fixture input is generated by our host. Production framing is in Protocol.ex.
const input=createInterface({input:process.stdin});
input.on('line',line=>{try{handle(JSON.parse(line)).catch(e=>process.stderr.write(String(e)+'\n'));}catch{}});
input.on('close',()=>process.exit(0));
