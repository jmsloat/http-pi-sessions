// Browser coverage for saved sessions, workspace navigation, and independent drafts.
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.TEST_BASE_URL || 'http://localhost:4000';
const out=process.env.TEST_OUTPUT_DIR || '/tmp/desk-session-browser';
mkdirSync(out,{recursive:true});
for(let i=0;i<100;i++){try{if((await fetch(base+'/health')).ok)break;}catch{}await new Promise(r=>setTimeout(r,200));}
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[];
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(base);await page.waitForSelector('.phx-connected');await page.waitForURL('**/sessions/**');
  const firstUrl=page.url();
  assert.ok(await page.locator('#resume-session').isVisible());
  assert.equal(await page.locator('.markdown pre code').count(),1);
  assert.equal(await page.locator('.markdown script').count(),0);
  await page.getByLabel('Message your agent').fill('Draft for the first session');
  await page.getByLabel('New session name').fill('Review workspace');
  await page.getByRole('button',{name:'+ New session',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('h1').textContent==='Review workspace');
  const secondUrl=page.url();
  assert.notEqual(firstUrl,secondUrl);
  assert.equal(await page.locator('.message').count(),0);
  assert.equal(await page.getByLabel('Message your agent').inputValue(),'');
  await page.getByLabel('Message your agent').fill('Draft for the second session');
  await page.locator('.session-link').filter({hasText:'First session'}).click();
  await page.waitForURL(firstUrl);
  assert.equal(await page.getByLabel('Message your agent').inputValue(),'Draft for the first session');
  await page.locator('.session-link').filter({hasText:'Review workspace'}).click();
  await page.waitForURL(secondUrl);
  assert.equal(await page.getByLabel('Message your agent').inputValue(),'Draft for the second session');
  await page.locator('#resume-session').click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent.includes('Ready'));
  await page.locator('#model-select').selectOption(JSON.stringify(['demo','scripted-fast']));
  await page.getByRole('button',{name:'Apply model',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent.includes('Ready') && !document.querySelector('#thinking-select'));
  await page.getByRole('button',{name:'Send',exact:false}).click();
  await page.getByText('Which behavior should we verify next?',{exact:true}).waitFor();
  const other=await context.newPage();other.on('pageerror',e=>errors.push(String(e)));
  await other.goto(firstUrl);await other.waitForSelector('.phx-connected');
  await other.locator('#resume-session').click();
  await other.getByRole('alert').filter({hasText:'Another session is working'}).waitFor();
  await page.getByRole('button',{name:'Stop',exact:false}).click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent.includes('Ready'));
  await other.locator('#resume-session').click();
  await other.waitForFunction(()=>document.querySelector('#session-status').textContent.includes('Ready'));
  await page.locator('#resume-session').waitFor();
  assert.equal(await page.locator('.message.user').count(),1);
  await page.getByText('Session settings',{exact:true}).click();
  await page.getByRole('button',{name:'Archive session',exact:true}).click();
  await page.getByRole('button',{name:'Restore session',exact:true}).waitFor();
  assert.equal(await page.locator('#resume-session').count(),0);
  await page.getByRole('button',{name:'Show archived',exact:true}).click();
  await page.screenshot({path:out+'/desktop-sessions.png',fullPage:true});
  await page.getByRole('button',{name:'Restore session',exact:true}).click();
  await page.locator('#resume-session').click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent.includes('Ready'));
  assert.equal(await page.locator('#model-select').inputValue(),JSON.stringify(['demo','scripted-fast']));
  assert.equal(await page.locator('.message.user').count(),1);
  await other.locator('#resume-session').waitFor();
  // Register another server directory and navigate to a saved conversation in it.
  await page.getByText('Add workspace',{exact:true}).click();
  await page.locator('#add-workspace input[name=name]').fill('Second project');
  await page.locator('#add-workspace input[name=path]').fill(process.env.TEST_WORKSPACE);
  await page.getByRole('button',{name:'Add directory',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#workspace-select').selectedOptions[0].textContent.includes('Second project'));
  await page.getByLabel('New session name').fill('Plan the next change');
  await page.getByRole('button',{name:'+ New session',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('h1').textContent==='Plan the next change');
  assert.equal(await page.locator('.message').count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Toggle workspaces',exact:true}).click();
  await page.getByLabel('Workspace',{exact:true}).selectOption({label:'desk-browser-workspace'});
  await page.locator('.session-link').filter({hasText:'First session'}).click();
  await page.waitForURL(firstUrl);
  assert.ok(await page.getByRole('button',{name:'Toggle workspaces',exact:true}).isVisible());
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile horizontal overflow');
  await page.screenshot({path:out+'/mobile-history.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks:['offline Markdown history','workspace registration','session create/switch','independent drafts','model persistence','busy workspace exclusion','two-tab suspend/resume','archive/restore','mobile navigation','no browser errors'],screenshots:out}));
} finally {await browser.close();}
